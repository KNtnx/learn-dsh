# -*- coding: utf-8 -*-
"""
rubric.py —— 第 2 章的"评分检查器"（模拟 harness 层的检查器约束）

harness engineering 的典型体现：光让模型输出还不够，要用【检查器】去验证
输出是否符合要求。本文件定义 8 项要点（评分清单）与检查函数，
第 3/4 层实验共用它作为"自动判分员"。

八项要点（对应任务书"学生 API 调用教程"任务的核心要求）：
  1. 前置条件（注册账号/申请 key）
  2. API key 安全（环境变量、不泄露）
  3. 错误处理（401/429 等状态码）
  4. 可复现步骤（命令可复制）
  5. 示例代码
  6. 费用说明
  7. 官方文档/参考链接
  8. 流式/JSON 等进阶能力说明

注意局限（报告已说明）：check() 是【关键词级】匹配——命中关键词即算覆盖，
可能"表面覆盖"，观察真实实验时第 1 层就出现 8/8 但内容泛化的情况。
"""

# 评分清单：每项 =（名称, 命中关键词列表）
# 关键词设计原则：一个要点给 3-5 个常见说法，覆盖模型的不同表述
RUBRIC = [
    ("前置条件", ["注册", "申请", "key 获取", "账号"]),
    ("API key 安全", ["环境变量", "泄露", "安全", "脱敏", "不提交"]),
    ("错误处理", ["401", "429", "错误", "状态码", "限流", "重试"]),
    ("可复现步骤", ["步骤", "命令", "复制", "运行", "示例"]),
    ("示例代码", ["代码", "curl", "python", "脚本", "SDK"]),
    ("费用说明", ["费用", "价格", "计费", "token 用量", "免费额度"]),
    ("参考链接", ["http", "文档", "官网", "链接", "platform."]),
    ("进阶能力", ["流式", "stream", "JSON", "结构化输出", "多轮"]),
]


def check(text: str):
    """按 rubric 检查一段文本，返回【未通过】的要点名称列表。

    实现：对每一项，只要文本中出现任一关键词（不区分大小写）就算覆盖；
    全部关键词都没出现 => 该项未覆盖，加入 missed。
    返回（8 - len(missed)）就是"覆盖了几项"
    """
    missed = []
    for name, kws in RUBRIC:
        # any(...)：任一关键词命中即通过该项
        if not any(kw.lower() in text.lower() for kw in kws):
            missed.append(name)
    return missed


def format_rubric() -> str:
    """生成人类可读的评分清单（会传给模型的提示词片段）。
    给模型"知道评分标准"，是 harness 约束的一部分。"""
    lines = ["评分检查清单（rubric）："]
    for i, (name, kws) in enumerate(RUBRIC, 1):
        # 只展示每个要点的前 3 个关键词，提示词保持精简
        lines.append(f"  {i}. {name}（关键词：{'/'.join(kws[:3])}...）")
    return "\n".join(lines)


if __name__ == "__main__":
    # 自测：只有关键词命中逻辑（不改模型，本地验证）
    import sys
    sample = "注册账号并申请 API key，把 key 放入环境变量避免泄露。"
    print("通过项数：", 8 - len(check(sample)))
